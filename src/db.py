def check_database_identity(conn: Connection) -> bool:
    """当前库是否已完成本项目 schema 初始化（供启动自检/测试使用）。"""
    if not table_exists(conn, "meta"):
        return False
    rows = {
        str(r["key"]): str(r["value"])
        for r in conn.execute("SELECT key, value FROM meta").fetchall()
    }
    return (rows.get("schema_version") == SCHEMA_VERSION
            and rows.get("schema_digest") == schema_digest())


